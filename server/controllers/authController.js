// UPDATE PROFILE (Protected)
const updateProfile = async (req, res) => {
  try {
    const user = await User.findById(req.user._id);

    if (!user) {
      return res.status(404).json({ message: "User not found" });
    }

    user.targetRole = req.body.targetRole ?? user.targetRole;
    user.experienceLevel = req.body.experienceLevel ?? user.experienceLevel;
    user.education = req.body.education ?? user.education;
    user.githubUsername = req.body.githubUsername ?? user.githubUsername;
    user.leetcodeUsername = req.body.leetcodeUsername ?? user.leetcodeUsername;

    const updatedUser = await user.save();

    res.status(200).json({
      _id: updatedUser._id,
      name: updatedUser.name,
      email: updatedUser.email,
      targetRole: updatedUser.targetRole,
      experienceLevel: updatedUser.experienceLevel,
      education: updatedUser.education,
      githubUsername: updatedUser.githubUsername,
      leetcodeUsername: updatedUser.leetcodeUsername,
    });
  } catch (error) {
    console.error(error);
    res.status(500).json({ message: "Server error" });
  }
};

module.exports = { registerUser, loginUser, getProfile, updateProfile };